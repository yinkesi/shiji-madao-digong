import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import {loadCore,placeEnemy} from './harness.mjs';
const ctx=loadCore();ctx.window=ctx;ctx.MDG.Terrain={TILE:42};
vm.runInContext(readFileSync(new URL('../js/combat-fx.js',import.meta.url),'utf8'),ctx);
const {Engine,Grid,CombatFX:F}=ctx.MDG;
const G=Engine.newRunState({seed:'combat-fx',runnerId:'yinkesi',diffV:'normal',meta:{}});
G.enemies=[];const p=G.player;
Grid.set(G.map,p.x+1,p.y,Grid.FLOOR);
const e=placeEnemy(ctx,G,'mob',p.x+1,p.y,{aggro:true});e.hp=e.maxHp=30;
G._visible={[p.x+','+p.y]:1,[e.x+','+e.y]:1};
const events=Engine.act(G,{t:'move',dx:1,dy:0});
const swing=events.find(v=>v.t==='swing'),hit=events.find(v=>v.t==='hit');
assert.equal(swing.uid,p.uid);assert.equal(swing.targetUid,e.uid);
assert.equal(hit.uid,e.uid);assert.equal(hit.hpBefore,30);assert.equal(hit.fromX,p.x);
const before=JSON.stringify(G);F.consume(G,events,1000);
assert.ok(F.pose(p,1030).x>0);assert.ok(F.pose(e,1030).x>0);
assert.ok(F.pose(e,1030).flash>0);assert.equal(F.pose(e,1030).trail,30);
assert.equal(F.pose(p,1600).x,0);assert.equal(F.pose(e,1600).flash,0);
assert.equal(JSON.stringify(G),before,'presentation must not change combat state');
F.reset();F.consume(G,[{...hit,zero:true,dmg:0}],2000);
assert.equal(F.pose(e,2030).flash,0);assert.ok(F.pose(e,2030).guard>0);
F.reset();F.consume(G,[{...hit,t:'miss'}],3000);
assert.ok(F.pose(e,3120).y>0);assert.equal(F.pose(e,3120).flash,0);
F.reset();G._visible={};F.consume(G,events,4000);assert.equal(F.pose(p,4030).x,0);
console.log('✓ combat-fx: directed events, recoil, health trail, guard, dodge, expiry, visibility and state isolation');
